/** Tokens the studio reads to draw an imported pack's preview strip. */
const PREVIEW_TOKENS = [
  '--dsw-specific-sidebar-fill',
  '--dsw-alias-brand-primary',
  '--dsw-alias-state-warn-primary',
] as const

/**
 * Derive a preview strip from an imported pack's own tokens.
 * @param tokens - validated pack tokens.
 * @returns three colors; missing tokens fall back to the surface ink.
 */
export function previewSwatches(tokens: ThemePackTokens): readonly [string, string, string] {
  const fallback = tokens['--dsw-alias-label-primary'] ?? '#808080'
  return [
    tokens[PREVIEW_TOKENS[0]] ?? fallback,
    tokens[PREVIEW_TOKENS[1]] ?? fallback,
    tokens[PREVIEW_TOKENS[2]] ?? fallback,
  ]
}
