/**
 * Built-in theme packs: complete alias-token palettes layered over the base
 * light or dark stylesheet. Each pack covers the surfaces, borders, ink,
 * controls, states, code, scrollbars, overlays, and sidebar tokens the shell
 * draws with, so switching a pack repaints the whole harness rather than an
 * accent. Values are data, not component styles: the runtime applies them as
 * inline CSS variables on `body`.
 */
import type { ThemeKey } from './locales.ts'

/** One pack's alias-token values, keyed by `--dsw-*` variable name. */
export type ThemePackTokens = Readonly<Record<string, string>>

/**
 * One selectable theme pack.
 * Built-in packs carry locale keys; imported packs carry the author's own name
 * and description verbatim.
 */
export interface ThemePack {
  /** Stable pack id used by selection and persistence. */
  readonly id: string
  /** Base palette the pack is drawn for; selecting the pack selects that scheme. */
  readonly colorScheme: 'light' | 'dark'
  /** Complete alias-token values applied over the base palette. */
  readonly tokens: ThemePackTokens
  /** Three representative colors for the studio preview strip. */
  readonly swatches: readonly [string, string, string]
  /** Whether the pack ships with the plugin; imported packs can be removed. */
  readonly builtin: boolean
  /** Localized name key of a built-in pack. */
  readonly nameKey?: ThemeKey
  /** Author-supplied name of an imported pack. */
  readonly name?: string
  /** Localized description key of a built-in pack. */
  readonly descriptionKey?: ThemeKey
  /** Author-supplied description of an imported pack. */
  readonly description?: string
}

